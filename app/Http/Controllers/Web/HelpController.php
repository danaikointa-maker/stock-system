    public function show(Request $request)
    {
        $path = $request->input('page', 'dashboard');
        $user = auth()->user();

        $guide = $this->getGuide($path, $user);

        return response()->json($guide);
    }

    private function getGuide(string $path, $user): array
    {
        $guides = $this->allGuides();

        // หา guide ที่ตรงกับ path
        foreach ($guides as $key => $guide) {
            if ($key === $path || str_starts_with($path, $key)) {
                return $guide;
            }
        }

        // default
        return $guides['dashboard'] ?? [
            'title' => 'คู่มือการใช้งาน',
            'content' => '<p>เลือกหัวข้อจากเมนูด้านซ้ายเพื่อดูคู่มือ</p>',
        ];
    }

