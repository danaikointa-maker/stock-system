    public function show(Request $request)
    {
        $page = $request->input('page', '');
        $user = auth()->user();

        $all = $this->allGuides();

        // กรองเฉพาะที่ user มีสิทธิ์
        $accessible = [];
        foreach ($all as $key => $g) {
            $needs = $g['abilities'] ?? [];
            if (empty($needs) || $this->userHasAny($user, $needs)) {
                $accessible[$key] = [
                    'key' => $key,
                    'icon' => $g['icon'] ?? '📄',
                    'label' => $g['label'] ?? $key,
                ];
            }
        }

        // ถ้าไม่ได้ระบุ page หรือ page ที่ขอไม่มีสิทธิ์ → detect จาก URL
        if (!$page || !isset($all[$page]) || !isset($accessible[$page])) {
            $page = $this->detectFromReferer($request, $accessible);
        }

        $guide = $all[$page] ?? $all['getting-started'];

        return response()->json([
            'title' => ($guide['icon'] ?? '📄') . ' ' . ($guide['label'] ?? 'คู่มือ'),
            'content' => $guide['content'] ?? '<p>ไม่มีเนื้อหา</p>',
            'pages' => array_values($accessible),
            'current' => $page,
        ]);
    }

    private function detectFromReferer(Request $request, array $accessible): string
    {
        $ref = $request->input('url', '');
        if (!$ref) {
            return array_key_first($accessible) ?: 'getting-started';
        }

        $map = [
            'pos/history' => 'pos-history',
            'pos' => 'pos',
            'redeem/history' => 'redeem-history',
            'redeem' => 'redeem',
            'products/quick-stock' => 'quick-stock',
            'products' => 'products',
            'reports/stock' => 'stock',
            'reports/movements' => 'movements',
            'reports/summary' => 'reports',
            'reports/qr' => 'qr-reports',
            'transfers' => 'transfers',
            'stock/count' => 'stock-count',
            'customers/rewards' => 'rewards',
            'customers' => 'customers',
            'nodes' => 'nodes',
            'members' => 'members',
            'subscriptions' => 'subscriptions',
            'claims' => 'claims',
            'admin/claims' => 'admin-claims',
            'admin/packages' => 'packages',
            'admin/security' => 'security',
            'admin/settings' => 'settings',
            'shop' => 'shop',
            'profile' => 'profile',
            'dashboard' => 'dashboard',
        ];

        $path = parse_url($ref, PHP_URL_PATH) ?: $ref;
        $path = ltrim($path, '/');

        // ตัด base path ออก
        $scriptName = $_SERVER['SCRIPT_NAME'] ?? '';
        if (preg_match('#^(.+)/public/index\.php$#', $scriptName, $m)) {
            $base = ltrim($m[1], '/') . '/';
            if (str_starts_with($path, $base)) {
                $path = substr($path, strlen($base));
            }
        } elseif (preg_match('#^(.+)/index\.php$#', $scriptName, $m)) {
            $base = ltrim($m[1], '/') . '/';
            if ($base !== 'public/' && str_starts_with($path, $base)) {
                $path = substr($path, strlen($base));
            }
        }

        // match จากยาวไปสั้น
        uksort($map, fn($a, $b) => strlen($b) - strlen($a));
        foreach ($map as $prefix => $key) {
            if (str_starts_with($path, $prefix) && isset($accessible[$key])) {
                return $key;
            }
        }

        return array_key_first($accessible) ?: 'getting-started';
    }

    private function userHasAny($user, array $abilities): bool
    {
        foreach ($abilities as $ability) {
            if ($user->hasAbility($ability)) {
                return true;
            }
        }
        return false;
    }

